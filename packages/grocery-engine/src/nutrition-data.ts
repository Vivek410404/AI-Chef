/**
 * Returns nutritional data for an ingredient or calculates a transparent, clearly-attributed estimate
 * when exact entry is unavailable.
 */
export function getIngredientNutritionProfile(
  ingredientId: string,
  fallbackName?: string,
  fallbackCategory?: string
): { profile: IngredientNutritionalProfile; isEstimate: boolean } {
  if (INGREDIENT_NUTRITION_DATABASE[ingredientId]) {
    return {
      profile: INGREDIENT_NUTRITION_DATABASE[ingredientId],
      isEstimate: false
    };
  }

  // Transparent, documented category fallback estimate for unknown items
  const name = fallbackName || ingredientId;
  const category = fallbackCategory || 'Pantry Staples';

  let estimatedMacros = {
    calories: 120,
    protein: 3.0,
    carbs: 15.0,
    fat: 4.0,
    fiber: 2.0,
    sugar: 1.0,
    sodium: 20
  };

  if (category === 'Produce') {
    estimatedMacros = { calories: 35, protein: 1.5, carbs: 7.0, fat: 0.2, fiber: 2.5, sugar: 3.0, sodium: 10 };
  } else if (category === 'Lentils & Pulses') {
    estimatedMacros = { calories: 345, protein: 22.0, carbs: 60.0, fat: 2.0, fiber: 16.0, sugar: 1.5, sodium: 20 };
  } else if (category === 'Grains & Atta') {
    estimatedMacros = { calories: 350, protein: 10.0, carbs: 74.0, fat: 2.0, fiber: 5.0, sugar: 1.0, sodium: 10 };
  } else if (category === 'Dairy & Eggs') {
    estimatedMacros = { calories: 150, protein: 8.0, carbs: 5.0, fat: 10.0, fiber: 0.0, sugar: 4.0, sodium: 80 };
  } else if (category === 'Spices & Masalas') {
    estimatedMacros = { calories: 300, protein: 12.0, carbs: 50.0, fat: 12.0, fiber: 20.0, sugar: 2.0, sodium: 50 };
  } else if (category === 'Oils & Ghee') {
    estimatedMacros = { calories: 884, protein: 0.0, carbs: 0.0, fat: 100.0, fiber: 0.0, sugar: 0.0, sodium: 0 };
  }

  const profile: IngredientNutritionalProfile = {
    ingredientId,
    ingredientName: name,
    perAmount: 100,
    perUnit: 'g',
    ...estimatedMacros,
    source: 'ESTIMATE',
    sourceAttribution: `Estimated Culinary Benchmark for ${category} (Pending IFCT laboratory analysis)`,
    confidence: 'estimate',
    notes: 'Estimated value based on typical culinary category averages. Not measured in lab.'
  };

  return { profile, isEstimate: true };
}
